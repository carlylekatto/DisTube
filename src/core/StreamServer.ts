import { randomBytes } from "node:crypto";
import { createServer, type IncomingMessage, type Server, type ServerResponse } from "node:http";
import { Readable } from "node:stream";

/**
 * A request of the stream server.
 */
export interface StreamRequest {
  /**
   * The path after the source, e.g. `v/abc123`.
   */
  path: string;
  /**
   * The parsed query parameters.
   */
  query: URLSearchParams;
  /**
   * The byte offset the client asked for, or `0`.
   */
  offset: number;
  /**
   * Aborted when the client disconnects.
   */
  signal: AbortSignal;
  /**
   * The raw request.
   */
  request: IncomingMessage;
}

/**
 * The response of a stream handler.
 */
export interface StreamResponse {
  /**
   * The audio bytes.
   */
  body: Readable | AsyncIterable<Uint8Array>;
  /**
   * The content type. Default: `application/octet-stream`.
   */
  contentType?: string;
  /**
   * The status code. Default: `200`.
   */
  status?: number;
  /**
   * The total size of the stream, when it is known.
   *
   * It is required to answer the range requests.
   */
  size?: number;
  /**
   * Extra headers.
   */
  headers?: Record<string, string | number>;
}

/**
 * The handler of a source.
 */
export type StreamHandler = (
  req: StreamRequest,
) => Promise<StreamResponse | null | undefined> | StreamResponse | null | undefined;

/**
 * A handle to release a resource.
 */
export interface Disposable {
  /**
   * Release the resource.
   */
  dispose(): void;
}

/**
 * Options of the stream server.
 */
export interface StreamServerOptions {
  /**
   * The port of the server. `0` (the default) lets the operating system pick a
   * free one, which is what a plugin should use: a fixed port makes the next
   * instance fail with `EADDRINUSE`.
   */
  port?: number;
  /**
   * The prefix of the URLs. A random one is generated by default, so the other
   * local processes cannot guess them.
   */
  prefix?: string;
}

const parseRange = (header: string | undefined): number => {
  if (!header) return 0;
  const match = /^bytes=(\d+)-/u.exec(header);
  return match ? Number(match[1]) : 0;
};

/**
 * A local HTTP server that the plugins use to stream the audio.
 *
 * Every plugin that cannot hand out a static URL to FFmpeg needs an HTTP
 * server: a source that has to be decrypted, captured or negotiated cannot be
 * fetched by FFmpeg directly. Instead of every plugin running its own server,
 * they register a handler on this one.
 *
 * The server is started on the first registration and it is closed by
 * {@link DisTube#destroy}.
 */
export class StreamServer {
  readonly #handlers = new Map<string, StreamHandler>();
  readonly #port: number;
  readonly #prefix: string;
  #server?: Server;
  #ready?: Promise<void>;
  #boundPort?: number;
  #closed = false;
  /**
   * Create a stream server.
   * @param options - Optional options
   */
  constructor({ port = 0, prefix }: StreamServerOptions = {}) {
    this.#port = port;
    this.#prefix = prefix ?? randomBytes(8).toString("hex");
  }
  /**
   * The prefix of the URLs of the server.
   */
  get prefix(): string {
    return this.#prefix;
  }
  /**
   * The base URL of the server, e.g. `http://127.0.0.1:51234`.
   *
   * @throws When the server is not started yet.
   */
  get baseUrl(): string {
    if (!this.#boundPort) throw new Error("The stream server is not started yet.");
    return `http://127.0.0.1:${this.#boundPort}`;
  }
  /**
   * Register a source.
   *
   * The handler is called for every request of that source. Return `null` to
   * answer a `404`.
   * @param source  - The identifier of the source
   * @param handler - The handler of the source
   * @returns A handle to unregister the source
   */
  register(source: string, handler: StreamHandler): Disposable {
    const key = source.toLowerCase();
    this.#handlers.set(key, handler);
    void this.#start();
    return {
      dispose: () => {
        if (this.#handlers.get(key) === handler) this.#handlers.delete(key);
      },
    };
  }
  /**
   * Build the URL of a stream.
   *
   * The server is started when it is not running yet.
   * @param source - The identifier of the source
   * @param path   - The path after the source
   * @param query  - The query parameters
   * @returns The URL of the stream
   */
  async url(source: string, path?: string, query?: Record<string, string | number | boolean>): Promise<string> {
    await this.#start();
    const url = new URL(`${this.baseUrl}/${this.#prefix}/${source.toLowerCase()}`);
    if (path) url.pathname = `${url.pathname}/${path.replace(/^\/+/u, "")}`;
    for (const [key, value] of Object.entries(query ?? {})) url.searchParams.set(key, String(value));
    return url.toString();
  }
  /**
   * Close the server and release every handler.
   */
  async close(): Promise<void> {
    this.#closed = true;
    this.#handlers.clear();
    const server = this.#server;
    this.#server = undefined;
    this.#ready = undefined;
    this.#boundPort = undefined;
    if (!server) return;
    await new Promise<void>(resolve => server.close(() => resolve()));
  }
  async #start(): Promise<void> {
    if (this.#closed) throw new Error("The stream server is closed.");
    if (!this.#ready) {
      this.#ready = new Promise<void>((resolve, reject) => {
        const server = createServer((req, res) => void this.#handle(req, res));
        server.once("error", reject);
        server.listen(this.#port, "127.0.0.1", () => {
          const address = server.address();
          this.#boundPort = typeof address === "object" && address ? address.port : this.#port;
          this.#server = server;
          // The server must not keep the process alive.
          server.unref?.();
          resolve();
        });
      });
    }
    return this.#ready;
  }
  async #handle(req: IncomingMessage, res: ServerResponse): Promise<void> {
    const controller = new AbortController();
    req.on("close", () => controller.abort());
    try {
      const requestUrl = new URL(req.url ?? "/", "http://127.0.0.1");
      const segments = requestUrl.pathname.split("/").filter(Boolean);
      if (segments[0] !== this.#prefix) {
        res.writeHead(404, { "Content-Type": "text/plain" }).end("Not Found");
        return;
      }
      const handler = this.#handlers.get((segments[1] ?? "").toLowerCase());
      if (!handler) {
        res.writeHead(404, { "Content-Type": "text/plain" }).end("Not Found");
        return;
      }
      const result = await handler({
        path: segments.slice(2).join("/"),
        query: requestUrl.searchParams,
        offset: parseRange(req.headers.range),
        signal: controller.signal,
        request: req,
      });
      if (!result) {
        res.writeHead(404, { "Content-Type": "text/plain" }).end("Not Found");
        return;
      }
      const headers: Record<string, string | number> = {
        "Content-Type": result.contentType ?? "application/octet-stream",
        ...result.headers,
      };
      if (result.size !== undefined) headers["Accept-Ranges"] = "bytes";
      if (result.size !== undefined && result.size > 0) {
        const offset = Math.min(parseRange(req.headers.range), Math.max(result.size - 1, 0));
        if (offset > 0) {
          headers["Content-Range"] = `bytes ${offset}-${result.size - 1}/${result.size}`;
          res.writeHead(206, headers);
        } else {
          res.writeHead(result.status ?? 200, headers);
        }
      } else {
        res.writeHead(result.status ?? 200, headers);
      }
      const body = result.body instanceof Readable ? result.body : Readable.from(result.body);
      body.on("error", () => res.end());
      body.pipe(res);
    } catch {
      if (!res.headersSent) res.writeHead(500, { "Content-Type": "text/plain" });
      res.end();
    }
  }
}
